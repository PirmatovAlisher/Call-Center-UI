// Initialize jsPDF reference first
const jsPDF = window.jspdf.jsPDF;

// Attach autoTable plugin EXPLICITLY
jsPDF.autoTable = window.jspdfAutoTable;

// PDF Export Functions
function initializePDFExport() {
    window.exportToPDF = function (data, isLandscape, generatedBy) {
        return new Promise((resolve, reject) => {
            try {
                const doc = new jsPDF({
                    orientation: isLandscape ? "landscape" : "portrait",
                    unit: "mm",
                    format: "a4"
                });

                // 1. Define columns properly
                const headers = [
                    ["Agent Name", "Agent Number", "Call Time",
                        "Customer Type", "Account Number",
                        "Call Duration", "Caller Number"]
                ];

                // 2. Ensure data is in correct format
                const rows = data.map(call => [
                    call.agentName || "-",
                    call.agentNumber || "-",
                    call.callTime || "-",
                    call.customerType || "-",
                    call.accountNumber || "-",
                    formatDuration(call.callDurationSeconds || 0), // Safely handle undefined
                    call.callerNumber || "-"
                ]);

                // 3. Use proper autoTable configuration
                doc.autoTable({
                    head: headers,
                    body: rows,
                    startY: 20,
                    margin: { top: 20 },
                    styles: {
                        fontSize: 8,
                        cellPadding: 1.5,
                        valign: 'middle'
                    },
                    headerStyles: {
                        fillColor: [41, 128, 185],
                        textColor: 255,
                        fontSize: 9
                    },
                    theme: 'grid'
                });

                // Enhanced footer with multiple sections
                const pageCount = doc.getNumberOfPages();
                for (let i = 1; i <= pageCount; i++) {
                    doc.setPage(i);
                    doc.setFontSize(8);

                    // Left section
                    doc.text(
                        `Generated by ${generatedBy}`,
                        10, // x-position (left margin)
                        doc.internal.pageSize.height - 10,
                        { align: 'left' }
                    );

                    // Center section
                    doc.text(
                        `Exported on ${new Date().toLocaleDateString()}`,
                        doc.internal.pageSize.width / 2,
                        doc.internal.pageSize.height - 10,
                        { align: 'center' }
                    );

                    // Right section
                    doc.text(
                        `Page ${i} of ${pageCount}`,
                        doc.internal.pageSize.width - 10, // x-position (right margin)
                        doc.internal.pageSize.height - 10,
                        { align: 'right' }
                    );

                    // Inside footer loop
                    doc.setFontSize(8);
                    doc.setFont("helvetica", "normal");

                    // Add colored text
                    doc.setTextColor(100, 100, 100); // Grey color

                    // Add horizontal line above footer
                    doc.setLineWidth(0.2);
                    doc.line(
                        10, // x1
                        doc.internal.pageSize.height - 12, // y1
                        doc.internal.pageSize.width - 10, // x2
                        doc.internal.pageSize.height - 12 // y2
                    );                    
                }

                doc.save(`CallHistory_${new Date().toISOString().slice(0, 19)}.pdf`);
                resolve();
            } catch (e) {
                reject(e.toString());
            }
        });
    };
}

function formatDuration(seconds) {
    if (isNaN(seconds)) return "00:00"; // Handle invalid values
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
}

// Initialize when script loads
initializePDFExport();